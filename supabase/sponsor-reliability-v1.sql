alter table public.star_payments
  add column if not exists status text not null default 'confirmed',
  add column if not exists telegram_verified_at timestamptz,
  add column if not exists refunded_at timestamptz,
  add column if not exists refund_reason text,
  add column if not exists reconciliation_status text not null default 'pending',
  add column if not exists reconciliation_error text,
  add column if not exists admin_note text,
  add column if not exists updated_at timestamptz not null default now();

do $$ begin
  alter table public.star_payments add constraint star_payments_status_check
    check (status in ('confirmed','refunded','disputed','reconciliation_error'));
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.star_payments add constraint star_payments_reconciliation_status_check
    check (reconciliation_status in ('pending','verified','not_found','mismatch','refunded','error'));
exception when duplicate_object then null; end $$;

create index if not exists star_payments_status_idx
  on public.star_payments(status, created_at desc);
create index if not exists star_payments_reconciliation_idx
  on public.star_payments(reconciliation_status, created_at desc);

create table if not exists public.star_payment_events (
  id bigint generated by default as identity primary key,
  payment_id uuid references public.star_payments(id) on delete cascade,
  event_type text not null,
  actor_user_id uuid references auth.users(id) on delete set null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint star_payment_events_type_check check (event_type in (
    'payment_received','telegram_verified','payment_recovered','reconciliation_mismatch',
    'reconciliation_not_found','reconciliation_failed','refund_requested','refund_completed',
    'refund_failed','admin_note_updated'
  ))
);

create index if not exists star_payment_events_payment_idx
  on public.star_payment_events(payment_id, created_at desc);

