-- Sponsor totals must count only confirmed, non-refunded payments.
create or replace function public.update_sponsor_account_v2()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  k text;
begin
  if tg_op <> 'INSERT' and old.status = 'confirmed' then
    k := case when old.user_id is not null then 'u:' || old.user_id::text else 't:' || old.telegram_id::text end;
    update public.sponsor_accounts
       set total_stars = greatest(0, total_stars - old.amount),
           payment_count = greatest(0, payment_count - 1),
           updated_at = now()
     where account_key = k;
  end if;

  if tg_op <> 'DELETE' and new.status = 'confirmed' then
    k := case when new.user_id is not null then 'u:' || new.user_id::text else 't:' || new.telegram_id::text end;
    insert into public.sponsor_accounts(account_key,user_id,telegram_id,total_stars,payment_count)
      values(k,new.user_id,case when new.user_id is null then new.telegram_id else null end,new.amount,1)
    on conflict(account_key) do update
      set total_stars = public.sponsor_accounts.total_stars + excluded.total_stars,
          payment_count = public.sponsor_accounts.payment_count + 1,
          updated_at = now();
  end if;

  return null;
end
$$;

-- Keep updated_at current without relying on the application.
create or replace function public.touch_star_payment_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end
$$;

drop trigger if exists star_payments_touch_updated_at on public.star_payments;
create trigger star_payments_touch_updated_at
before update on public.star_payments
for each row execute function public.touch_star_payment_updated_at();
