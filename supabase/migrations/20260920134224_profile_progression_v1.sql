CREATE OR REPLACE FUNCTION public.community_metrics(p_user uuid)
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
  with completed_episode_rows as (
    select e.anime_id, e.episode_number
    from animebox_watch.progress p
    join animebox_watch.episodes e on e.id = p.episode_id
    where p.user_id = p_user and p.completed_at is not null
  ),
  completed_titles as (
    select a.id, a.genres
    from public.anime_catalog a
    join completed_episode_rows h on h.anime_id = a.id
    where a.finished and a.total_episodes is not null
      and h.episode_number <= a.total_episodes
    group by a.id, a.genres, a.total_episodes
    having count(distinct h.episode_number) >= a.total_episodes
  ),
  watch_totals as (
    select
      count(*) filter (where p.completed_at is not null)::bigint as completed_episodes,
      coalesce(sum(p.active_ms), 0)::bigint as active_ms
    from animebox_watch.progress p
    where p.user_id = p_user
  )
  select jsonb_build_object(
    'episodes',(select completed_episodes from watch_totals),
    'titles',(select count(*) from completed_titles),
    'minutes',(select floor(active_ms / 60000.0)::bigint from watch_totals),
    'watch_minutes',(select floor(active_ms / 60000.0)::bigint from watch_totals),
    'active_ms',(select active_ms from watch_totals),
    'shonen_titles',(select count(*) from completed_titles where genres && array['Shounen','Shonen','Сёнен','Сенен']),
    'romance_titles',(select count(*) from completed_titles where genres && array['Romance','Романтика']),
    'action_titles',(select count(*) from completed_titles where genres && array['Action','Экшен']),
    'fantasy_titles',(select count(*) from completed_titles where genres && array['Fantasy','Фэнтези']),
    'comedy_titles',(select count(*) from completed_titles where genres && array['Comedy','Комедия']),
    'comments',(select count(*) from public.comments where user_id=p_user and deleted_at is null),
    'watching',(select count(*) from public.anime_library where user_id=p_user and status='watching'),
    'planned',(select count(*) from public.anime_library where user_id=p_user and status='planned'),
    'completed',(select count(*) from public.anime_library where user_id=p_user and status='completed'),
    'dropped',(select count(*) from public.anime_library where user_id=p_user and status='dropped')
  );
$function$;

CREATE OR REPLACE FUNCTION public.sync_user_progression(p_user uuid, p_premium_boost boolean, p_event_key text, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  metrics jsonb;
  current_row public.user_progression%rowtype;
  target_episodes bigint; target_titles bigint; target_watch_buckets bigint; target_comments bigint;
  delta_episodes bigint; delta_titles bigint; delta_watch_buckets bigint; delta_comments bigint;
  activity_gain bigint := 0; premium_gain bigint := 0; achievement_gain bigint := 0;
  unlocked jsonb := '[]'::jsonb; result jsonb;
begin
  if p_user is null then raise exception 'INVALID_USER'; end if;
  if p_event_key is null or length(trim(p_event_key))=0 or length(p_event_key)>180 then
    raise exception 'INVALID_EVENT_KEY';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_user::text,417));
  metrics := public.community_metrics(p_user);

  insert into public.user_progression(user_id) values(p_user)
  on conflict(user_id) do nothing;

  select * into current_row
  from public.user_progression
  where user_id=p_user
  for update;

  target_episodes := greatest(0,coalesce((metrics->>'episodes')::bigint,0));
  target_titles := greatest(0,coalesce((metrics->>'titles')::bigint,0));
  target_watch_buckets := greatest(0,floor(coalesce((metrics->>'active_ms')::numeric,0)/1800000.0)::bigint);
  target_comments := least(50,greatest(0,coalesce((metrics->>'comments')::bigint,0)));

  delta_episodes := greatest(0,target_episodes-current_row.credited_episodes);
  delta_titles := greatest(0,target_titles-current_row.credited_titles);
  delta_watch_buckets := greatest(0,target_watch_buckets-current_row.credited_watch_buckets);
  delta_comments := greatest(0,target_comments-current_row.credited_comments);

  activity_gain := delta_episodes*10 + delta_titles*75 + delta_watch_buckets*15 + delta_comments*2;
  if coalesce(p_premium_boost,false) and activity_gain>0 then
    premium_gain := floor(activity_gain*0.20)::bigint;
  end if;

  with eligible as (
    select a.code from public.achievements a
    where not a.hidden and coalesce((metrics->>a.metric)::bigint,0)>=a.threshold
  ),
  inserted as (
    insert into public.user_achievements(user_id,achievement_code)
    select p_user,e.code from eligible e
    on conflict do nothing
    returning achievement_code
  )
  select
    coalesce(sum(a.xp_reward),0)::bigint,
    coalesce(jsonb_agg(jsonb_build_object(
      'code',a.code,'title',a.title,'rarity',a.rarity,'xpReward',a.xp_reward
    ) order by a.sort_order,a.code),'[]'::jsonb)
  into achievement_gain,unlocked
  from inserted i join public.achievements a on a.code=i.achievement_code;

  update public.user_progression set
    activity_xp=activity_xp+activity_gain,
    premium_bonus_xp=premium_bonus_xp+premium_gain,
    achievement_xp=achievement_xp+achievement_gain,
    total_xp=total_xp+activity_gain+premium_gain+achievement_gain,
    credited_episodes=greatest(credited_episodes,target_episodes),
    credited_titles=greatest(credited_titles,target_titles),
    credited_watch_buckets=greatest(credited_watch_buckets,target_watch_buckets),
    credited_comments=greatest(credited_comments,target_comments),
    updated_at=now()
  where user_id=p_user;

  if activity_gain+premium_gain+achievement_gain>0 then
    insert into public.progression_events(
      user_id,event_key,reason,base_xp,premium_bonus_xp,achievement_xp,total_xp
    ) values (
      p_user,p_event_key,left(p_reason,120),
      activity_gain::integer,premium_gain::integer,achievement_gain::integer,
      (activity_gain+premium_gain+achievement_gain)::integer
    )
    on conflict(user_id,event_key) do nothing;
  end if;

  select jsonb_build_object(
    'total_xp',total_xp,'activity_xp',activity_xp,
    'premium_bonus_xp',premium_bonus_xp,'achievement_xp',achievement_xp,
    'credited_episodes',credited_episodes,'credited_titles',credited_titles,
    'credited_watch_buckets',credited_watch_buckets,'credited_comments',credited_comments,
    'earned_now',activity_gain+premium_gain+achievement_gain,
    'premium_bonus_now',premium_gain,'unlocked',unlocked,'updated_at',updated_at
  )
  into result from public.user_progression where user_id=p_user;

  return result;
end;
$function$;

CREATE OR REPLACE FUNCTION public.award_achievements(p_user uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  perform public.sync_user_progression(
    p_user,false,
    'legacy-award:' || floor(extract(epoch from clock_timestamp())*1000)::bigint::text,
    'legacy'
  );
end;
$function$;

CREATE OR REPLACE FUNCTION public.my_community_profile()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare uid uuid:=auth.uid(); result jsonb;
begin
  if uid is null then raise exception 'AUTH_REQUIRED'; end if;
  select jsonb_build_object(
    'stats',public.community_metrics(uid),
    'progression',coalesce(
      (select jsonb_build_object(
        'total_xp',p.total_xp,'activity_xp',p.activity_xp,
        'premium_bonus_xp',p.premium_bonus_xp,'achievement_xp',p.achievement_xp,
        'updated_at',p.updated_at
      ) from public.user_progression p where p.user_id=uid),
      jsonb_build_object(
        'total_xp',0,'activity_xp',0,'premium_bonus_xp',0,'achievement_xp',0,'updated_at',null
      )
    ),
    'achievements',(
      select coalesce(jsonb_agg(
        to_jsonb(a)||jsonb_build_object('earned_at',u.earned_at)
        order by a.sort_order,a.code
      ),'[]'::jsonb)
      from public.achievements a
      left join public.user_achievements u
        on u.achievement_code=a.code and u.user_id=uid
      where not a.hidden or u.earned_at is not null
    ),
    'library',(
      select coalesce(jsonb_agg(jsonb_build_object(
        'anime_id',l.anime_id,'title',a.title,'status',l.status
      ) order by l.updated_at desc),'[]'::jsonb)
      from public.anime_library l
      join public.anime_catalog a on a.id=l.anime_id
      where l.user_id=uid
    )
  ) into result;
  return result;
end;
$function$;


