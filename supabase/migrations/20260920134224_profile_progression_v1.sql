-- AnimeBox Profile Progression v1
-- Event-driven XP, Premium boost, richer achievements, and read-only profile progression.

alter table public.achievements
  drop constraint if exists achievements_metric_check;

alter table public.achievements
  add column if not exists category text not null default 'watch',
  add column if not exists rarity text not null default 'common',
  add column if not exists xp_reward integer not null default 25,
  add column if not exists hidden boolean not null default false,
  add column if not exists sort_order integer not null default 0;

alter table public.achievements
  add constraint achievements_metric_check
  check (metric = any (array[
    'episodes'::text,'titles'::text,'watch_minutes'::text,'comments'::text,
    'shonen_titles'::text,'romance_titles'::text,'action_titles'::text,
    'fantasy_titles'::text,'comedy_titles'::text
  ]));

alter table public.achievements drop constraint if exists achievements_rarity_check;
alter table public.achievements
  add constraint achievements_rarity_check
  check (rarity = any (array[
    'common'::text,'uncommon'::text,'rare'::text,'epic'::text,'legendary'::text
  ]));

alter table public.achievements drop constraint if exists achievements_xp_reward_check;
alter table public.achievements
  add constraint achievements_xp_reward_check
  check (xp_reward >= 0 and xp_reward <= 5000);

create index if not exists achievements_metric_threshold_idx
  on public.achievements(metric, threshold);

create table if not exists public.user_progression (
  user_id uuid primary key references auth.users(id) on delete cascade,
  total_xp bigint not null default 0,
  activity_xp bigint not null default 0,
  premium_bonus_xp bigint not null default 0,
  achievement_xp bigint not null default 0,
  credited_episodes bigint not null default 0,
  credited_titles bigint not null default 0,
  credited_watch_buckets bigint not null default 0,
  credited_comments bigint not null default 0,
  updated_at timestamptz not null default now()
);

alter table public.user_progression enable row level security;
revoke all on table public.user_progression from anon, authenticated;
grant select, insert, update, delete on table public.user_progression to service_role;

create table if not exists public.progression_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_key text not null,
  reason text,
  base_xp integer not null default 0,
  premium_bonus_xp integer not null default 0,
  achievement_xp integer not null default 0,
  total_xp integer not null default 0,
  created_at timestamptz not null default now(),
  unique(user_id, event_key)
);

alter table public.progression_events enable row level security;
revoke all on table public.progression_events from anon, authenticated;
grant select, insert, update, delete on table public.progression_events to service_role;

create index if not exists progression_events_user_created_idx
  on public.progression_events(user_id, created_at desc);

