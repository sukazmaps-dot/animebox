-- Import existing Telegram Stars into the unified ledger without changing
-- the legacy sponsor system. The unique(provider, external_id) key makes
-- this migration and future dual-writes idempotent.
insert into public.payment_transactions (
  user_id,
  provider,
  product_code,
  external_id,
  external_user_id,
  status,
  amount,
  currency,
  provider_status,
  provider_created_at,
  paid_at,
  refunded_at,
  metadata,
  created_at,
  updated_at
)
select
  sp.user_id,
  'telegram_stars',
  'sponsor_support',
  sp.telegram_payment_charge_id,
  sp.telegram_id::text,
  case
    when sp.status = 'refunded' then 'refunded'
    when sp.status = 'confirmed' then 'paid'
    when sp.status in ('disputed', 'reconciliation_error') then 'failed'
    else 'pending'
  end,
  sp.amount::numeric,
  sp.currency,
  sp.status,
  sp.created_at,
  case when sp.status in ('confirmed', 'refunded') then sp.created_at else null end,
  sp.refunded_at,
  jsonb_build_object(
    'legacy_star_payment_id', sp.id,
    'telegram_id', sp.telegram_id,
    'reconciliation_status', sp.reconciliation_status
  ),
  sp.created_at,
  coalesce(sp.updated_at, sp.created_at)
from public.star_payments sp
on conflict (provider, external_id) do nothing;

insert into public.payment_events (transaction_id, event_type, details, created_at)
select
  pt.id,
  'payment.imported',
  jsonb_build_object('source', 'star_payments'),
  pt.created_at
from public.payment_transactions pt
where pt.provider = 'telegram_stars'
  and not exists (
    select 1
    from public.payment_events pe
    where pe.transaction_id = pt.id
      and pe.event_type = 'payment.imported'
  );
