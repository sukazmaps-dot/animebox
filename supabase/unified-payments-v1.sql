-- AnimeBox Unified Payments v1
-- Additive migration: existing Telegram Stars / sponsor tables remain untouched.

create table if not exists public.payment_products (
  code text primary key,
  name text not null,
  product_type text not null check (product_type in ('support', 'donation', 'subscription', 'gift', 'admin')),
  active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.payment_transactions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid null references auth.users(id) on delete set null,
  provider text not null check (char_length(provider) between 2 and 64),
  product_code text not null references public.payment_products(code),
  external_id text not null check (char_length(external_id) between 1 and 255),
  external_user_id text null,
  status text not null check (status in ('pending', 'paid', 'failed', 'cancelled', 'partially_refunded', 'refunded')),
  amount numeric(18,4) not null check (amount >= 0),
  currency text not null check (char_length(currency) between 2 and 12),
  provider_status text null,
  provider_created_at timestamptz null,
  paid_at timestamptz null,
  refunded_at timestamptz null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider, external_id)
);

create index if not exists payment_transactions_user_created_idx
  on public.payment_transactions (user_id, created_at desc);
create index if not exists payment_transactions_provider_created_idx
  on public.payment_transactions (provider, created_at desc);
create index if not exists payment_transactions_status_created_idx
  on public.payment_transactions (status, created_at desc);
create index if not exists payment_transactions_product_code_idx
  on public.payment_transactions (product_code);

create table if not exists public.payment_events (
  id bigint generated by default as identity primary key,
  transaction_id uuid not null references public.payment_transactions(id) on delete cascade,
  event_type text not null check (char_length(event_type) between 3 and 100),
  actor_user_id uuid null references auth.users(id) on delete set null,
  provider_event_id text null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists payment_events_transaction_created_idx
  on public.payment_events (transaction_id, created_at desc);
create index if not exists payment_events_actor_user_idx
  on public.payment_events (actor_user_id)
  where actor_user_id is not null;
create unique index if not exists payment_events_provider_event_unique_idx
  on public.payment_events (transaction_id, provider_event_id)
  where provider_event_id is not null;

create table if not exists public.payment_provider_sync_state (
  provider text primary key,
  cursor text null,
  last_synced_at timestamptz null,
  last_error text null,
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.user_entitlements (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  entitlement text not null check (char_length(entitlement) between 2 and 100),
  source text not null check (char_length(source) between 2 and 64),
  source_id text not null default '',
  active boolean not null default true,
  starts_at timestamptz not null default now(),
  expires_at timestamptz null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, entitlement, source, source_id),
  check (expires_at is null or expires_at > starts_at)
);

create index if not exists user_entitlements_active_idx
  on public.user_entitlements (user_id, entitlement, active, expires_at);

alter table public.payment_products enable row level security;
alter table public.payment_transactions enable row level security;
alter table public.payment_events enable row level security;
alter table public.payment_provider_sync_state enable row level security;
alter table public.user_entitlements enable row level security;

