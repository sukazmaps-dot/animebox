import { createHash } from 'node:crypto';
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import sharp from 'sharp';

// Run manually after changing artwork; generated assets and manifest are committed.
const root = new URL('../public/brand/emojis/moods/', import.meta.url);
const output = new URL('compact/', root);
await mkdir(output, { recursive: true });
const entries = [];
for (const name of (await readdir(root)).filter((name) => name.endsWith('.webp')).sort()) {
  const input = new URL(name, root);
  const metadata = await sharp(input.pathname).metadata();
  if ((metadata.pages ?? 1) > 1) throw new Error(`Animated mood asset needs explicit handling: ${name}`);
  const bytes = await sharp(input.pathname)
    .resize(128, 128, { fit: 'inside', withoutEnlargement: true })
    .webp({ quality: 82, alphaQuality: 100, effort: 6 })
    .toBuffer();
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
  const filename = `${name.slice(0, -5)}.${hash}.webp`;
  await writeFile(new URL(filename, output), bytes);
  // Separate artwork requests from any cached pre-deploy 404 at the bare URL.
  entries.push(`  '${name}': '/brand/emojis/moods/compact/${filename}?v=mood-icons-v1',`);
  console.log(`${name}: ${bytes.length} bytes`);
}
await writeFile(new URL('../lib/mood-icon-assets.ts', import.meta.url),
  '// Generated by scripts/optimize-mood-icons.mjs. Content hashes make immutable caching safe.\n' +
  'export const MOOD_ICON_ASSETS = {\n' + entries.join('\n') + '\n} as const;\n');
