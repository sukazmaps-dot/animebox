const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const read = path => fs.readFileSync(path, 'utf8');
const source = read('lib/airing-countdown.ts');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const mod = { exports: {} };
new Function('module', 'exports', compiled)(mod, mod.exports);
const getAiringCountdown = mod.exports.getAiringCountdown;
const now = 1800000000000;
assert.deepEqual(getAiringCountdown(1800086400, now), { state: 'countdown', label: '1 д 0 ч' });
assert.deepEqual(getAiringCountdown(1800003723, now), { state: 'countdown', label: '1 ч 2 мин 3 сек' });
assert.deepEqual(getAiringCountdown(1800000302, now), { state: 'countdown', label: '5 мин 2 сек' });
assert.deepEqual(getAiringCountdown(1800000000, now), { state: 'elapsed', label: 'Время выхода прошло' });
assert.equal(getAiringCountdown(0, now), null);
assert.equal(getAiringCountdown(-1, now), null);
assert.equal(getAiringCountdown(1.5, now), null);
const anilist = read('lib/anilist.ts');
const animeType = read('types/anime.ts');
const page = read('app/anime/[slug]/page.tsx');
const component = read('components/AnimeDetailAiringCountdown.tsx');
const css = read('components/AnimeDetailAiringCountdown.module.css');
assert(anilist.includes('nextAiringEpisode { episode airingAt }'));
assert(anilist.includes('nextEpisodeAiringAt: media.nextAiringEpisode?.airingAt ?? null'));
assert(animeType.includes('nextEpisodeAiringAt?: number | null'));
assert(page.includes('<AnimeDetailAiringCountdown') && page.includes('airingAt={resolved.nextEpisodeAiringAt}'));
assert(component.includes('window.setInterval(update, 1000)'));
assert(component.includes('if (!hasSchedule) return;'), 'no idle interval when AniList has no confirmed airing slot');
assert(component.includes('aria-live="off"') && css.includes(".root[data-state='elapsed']"));
console.log('PASS anime detail countdown: AniList mapping, formatting, expiry, fallback and accessible timer');
